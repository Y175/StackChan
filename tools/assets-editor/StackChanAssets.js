/** StackChan resource-pack contract shared by the browser and host checks. */
export const ASSETS_PARTITION_SIZE = 4 * 1024 * 1024

/** Decode and validate XiaoZhi's mmap asset format; this is not a SPIFFS volume. */
export function decodeAssets(buffer) {
  if (buffer.byteLength < 12 || buffer.byteLength > ASSETS_PARTITION_SIZE) {
    throw new Error('StackChan 资源包长度不合法')
  }
  const view = new DataView(buffer)
  const count = view.getUint32(0, true)
  const length = view.getUint32(8, true)
  const tableSize = count * 44
  if (length !== buffer.byteLength - 12 || tableSize > length) {
    throw new Error('StackChan 资源包目录损坏')
  }
  const bytes = new Uint8Array(buffer)
  const checksum = bytes.subarray(12).reduce((sum, value) => (sum + value) & 0xffff, 0)
  if (checksum !== view.getUint32(4, true)) {
    throw new Error('StackChan 资源包校验失败')
  }
  const files = new Map()
  let previousEnd = 12 + tableSize
  for (let position = 12; position < 12 + tableSize; position += 44) {
    const nameBytes = bytes.slice(position, position + 32)
    const end = nameBytes.indexOf(0)
    if (end < 1) throw new Error('资源文件名未终止或为空')
    const filename = new TextDecoder('utf-8', { fatal: true }).decode(nameBytes.subarray(0, end))
    const size = view.getUint32(position + 32, true)
    const offset = 12 + tableSize + view.getUint32(position + 36, true)
    if (files.has(filename) || offset !== previousEnd || offset + 2 + size > buffer.byteLength ||
        bytes[offset] !== 0x5a || bytes[offset + 1] !== 0x5a) {
      throw new Error(`资源条目损坏: ${filename}`)
    }
    files.set(filename, {
      filename, data: buffer.slice(offset + 2, offset + 2 + size), size,
      width: view.getUint16(position + 40, true), height: view.getUint16(position + 42, true)
    })
    previousEnd = offset + 2 + size
  }
  if (previousEnd !== buffer.byteLength || !files.has('index.json')) {
    throw new Error('资源包缺少 index.json 或包含未引用数据')
  }
  return files
}

/** Preserve firmware-owned assets and default speech models when no replacement is selected. */
export function mergeStackChanAssets(generator, baseline, config) {
  const display = config.chip?.display
  if (config.chip?.model !== 'esp32s3' || display?.width !== 320 || display?.height !== 240 ||
      display?.color !== 'RGB565') {
    throw new Error('此编辑器仅支持 StackChan：ESP32-S3、320 × 240、RGB565')
  }
  const generated = new Map()
  for (const file of generator.files) {
    if (generated.has(file.filename) || new TextEncoder().encode(file.filename).length > 31) {
      throw new Error(`重复或过长的资源文件名: ${file.filename}`)
    }
    generated.set(file.filename, file)
  }
  const parseIndex = files => {
    const file = files.get('index.json')
    if (!file) throw new Error('缺少 index.json')
    return JSON.parse(new TextDecoder().decode(file.data))
  }
  const baseIndex = parseIndex(baseline)
  const customIndex = parseIndex(generated)
  const mergedIndex = { ...baseIndex, ...customIndex }
  const replaced = new Set(['index.json'])
  // These resources have an explicit replacement in the editor. Other files
  // (including StackChan's menus and onboarding images) remain mandatory.
  if (config.theme.wakeword.type !== 'none') {
    if (baseIndex.srmodels) replaced.add(baseIndex.srmodels)
    delete mergedIndex.multinet_model
    if (customIndex.multinet_model) mergedIndex.multinet_model = customIndex.multinet_model
  }
  if (config.theme.font.type !== 'none') {
    if (baseIndex.text_font) replaced.add(baseIndex.text_font)
    // A replacement font must not inherit Noto metadata belonging to the baseline.
    delete mergedIndex.text_font_meta
  }
  const customEmotions = config.theme.emoji.type !== 'none'
  if (customEmotions) {
    for (const emoji of baseIndex.emoji_collection || []) replaced.add(emoji.file)
  }
  mergedIndex.stackchan = {
    format: 1,
    custom_emotions: customEmotions,
    native_expression_effects: config.theme.emoji.nativeEffects === true,
    xiaozhi: '2.5.2'
  }
  for (const [name, file] of baseline) {
    if (replaced.has(name)) continue
    if (generated.has(name)) throw new Error(`自定义资源与 StackChan 系统文件重名: ${name}`)
    generator.addFile(name, file.data, file)
  }
  const indexFile = generated.get('index.json')
  indexFile.data = new TextEncoder().encode(JSON.stringify(mergedIndex)).buffer
  indexFile.size = indexFile.data.byteLength
  const names = new Set(generator.files.map(file => file.filename))
  for (const name of [mergedIndex.srmodels, mergedIndex.text_font,
    ...(mergedIndex.emoji_collection || []).map(emoji => emoji.file)].filter(Boolean)) {
    if (!names.has(name)) throw new Error(`资源索引引用了缺失文件: ${name}`)
  }
  const bytes = 12 + generator.files.reduce((sum, file) => sum + 46 + file.size, 0)
  if (bytes > ASSETS_PARTITION_SIZE) {
    throw new Error(`资源包 ${(bytes / 1048576).toFixed(2)} MB，超过 StackChan 的 4 MB；请减少表情或字体`)
  }
}

/** Load the baseline generated by this firmware, never a generic XiaoZhi resource pack. */
export async function addStackChanAssets(generator, config) {
  const response = await fetch(`${import.meta.env.BASE_URL}stackchan-base.bin`)
  if (!response.ok) throw new Error(`无法加载 StackChan 基础资源 (${response.status})，请重新运行 prepare.py`)
  mergeStackChanAssets(generator, decodeAssets(await response.arrayBuffer()), config)
}
